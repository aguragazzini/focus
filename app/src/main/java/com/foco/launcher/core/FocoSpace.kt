package com.foco.launcher.core

import androidx.compose.ui.unit.dp

/**
 * Shared spacing. One step above the 0.9.0 rhythm so pages, sheets, and lists
 * read less cramped. Icon glyphs stay 48dp. Hit targets stay at least [touch].
 */
object FocoSpace {
    val hair = 6.dp
    val gap = 12.dp
    val gapLg = 16.dp
    val section = 22.dp
    val page = 32.dp
    val sheet = 36.dp
    val touch = 48.dp
}
